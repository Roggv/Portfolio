// English, Catalan and Spanish.
// UI text lives in STRINGS below and is read with say('key', { n: 3 }).
// Content from content.js is read with tr(value). Anything missing falls back to English.
const KEY = 'museum-language';

export const LANGUAGES = [
  { code: 'en', name: 'English' },
  { code: 'ca', name: 'Català' },
  { code: 'es', name: 'Español' },
];

const codes = LANGUAGES.map((l) => l.code);

// saved choice, then the browser language, then English
function initial() {
  try {
    const saved = localStorage.getItem(KEY);
    if (codes.includes(saved)) return saved;
  } catch { /* fall through */ }
  for (const tag of navigator.languages ?? [navigator.language]) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (codes.includes(code)) return code;
  }
  return 'en';
}

let current = initial();
const listeners = new Set();
document.documentElement.lang = current;

export const getLanguage = () => current;

export function setLanguage(code) {
  if (!codes.includes(code) || code === current) return;
  current = code;
  document.documentElement.lang = code;
  try { localStorage.setItem(KEY, code); } catch { /* storage blocked */ }
  listeners.forEach((fn) => fn(code));
}

export function onLanguage(fn) {
  listeners.add(fn);
}

export function tr(value) {
  if (value == null || typeof value !== 'object' || Array.isArray(value)) return value;
  return value[current] ?? value.en ?? Object.values(value)[0];
}

